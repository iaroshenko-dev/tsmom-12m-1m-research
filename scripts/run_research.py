"""Portable execution of original frozen scripts; original source files not modified.
By design, historical outputs in results/ remain immutable. Recreated files go to generated/.
"""
from pathlib import Path
import subprocess, sys, os
ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data/vendor/trendfollowing/resources/futures'
OUT = ROOT / 'generated/reproduction'
OLD_DATA = "Path('/mnt/data/quant_research_2_wheel/trendfollowing/resources/futures')"
OLD_OUTPUT = "Path('/mnt/data/quant_research_2_phase2')"
def run(filename):
    src = ROOT / 'research/original' / filename
    s = src.read_text(encoding='utf-8')
    if s.count(OLD_DATA) != 1 or s.count(OLD_OUTPUT) != 1:
        raise RuntimeError(f'Cannot safely patch fixed paths in frozen {filename}')
    s = s.replace(OLD_DATA, f'Path({str(DATA)!r})').replace(OLD_OUTPUT, f'Path({str(OUT)!r})')
    exe = OUT / ('portable_' + filename)
    exe.write_text(s, encoding='utf-8')
    env = os.environ.copy()
    env.setdefault('OPENBLAS_NUM_THREADS','1')
    subprocess.run([sys.executable, str(exe)], cwd=ROOT, env=env, check=True)
def main():
    for name in ('tf_system_data_usd_returns.csv','tf_system_data_volume_costs.csv','tf_system_data_descriptive_df.csv'):
        if not (DATA/name).is_file(): raise SystemExit('Source data missing. Run python scripts/fetch_data.py first.')
    OUT.mkdir(parents=True,exist_ok=True)
    run('quant_research_2_phase2.py')
    run('quant_research_2_phase2_extra.py')
    print('Reproduced results in', OUT)
    print('NOTE: archived signal_definition_robustness.csv was generated by a distinct analysis not present in the original ZIP scripts.')
    print('Run scripts/reproduce_signal_robustness.py to reconstruct and check this separately.')
if __name__ == '__main__': main()
